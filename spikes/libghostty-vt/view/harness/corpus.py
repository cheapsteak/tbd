#!/usr/bin/env python3
"""Prints the rendering corpus for one section, then stays alive so the screen can be shot."""
import sys, time
ESC = "\033"
def p(s=""): sys.stdout.write(s + "\n")
def colors():
    p("256 colours:")
    for start in (0, 16, 52, 88, 124, 160, 196, 232):
        n = 16 if start == 0 else (24 if start == 232 else 36)
        p("".join(f"{ESC}[48;5;{i}m  " for i in range(start, start + n)) + f"{ESC}[0m")
    p("foreground 0-15 and bold 0-7 (bold brightening):")
    p("".join(f"{ESC}[38;5;{i}m#{i:<3}" for i in range(16)) + f"{ESC}[0m")
    p("".join(f"{ESC}[1;3{i}m bold{i}" for i in range(8)) + f"{ESC}[0m")
    p("truecolor gradient, 80 steps:")
    p("".join(f"{ESC}[48;2;{i*3};{255-i*3};128m " for i in range(80)) + f"{ESC}[0m")
    p("".join(f"{ESC}[38;2;255;{i*3};0m█" for i in range(80)) + f"{ESC}[0m")
    p("inverse default, inverse colour, faint, invisible[between brackets]:")
    p(f"{ESC}[7m inverse {ESC}[0m {ESC}[7;31m inverse red {ESC}[0m {ESC}[2mfaint{ESC}[0m [{ESC}[8mhidden{ESC}[0m]")
def box():
    p("box drawing light/heavy/double/mixed/arcs:")
    p("┌──┬──┐ ┏━━┳━━┓ ╔══╦══╗ ╒══╤══╕ ╭──┬──╮ ╓──╥──╖")
    p("│  │  │ ┃  ┃  ┃ ║  ║  ║ │  │  │ │  │  │ ║  ║  ║")
    p("├──┼──┤ ┣━━╋━━┫ ╠══╬══╣ ╞══╪══╡ ├──┼──┤ ╟──╫──╢")
    p("│  │  │ ┃  ┃  ┃ ║  ║  ║ │  │  │ │  │  │ ║  ║  ║")
    p("└──┴──┘ ┗━━┻━━┛ ╚══╩══╝ ╘══╧══╛ ╰──┴──╯ ╙──╨──╜")
    p("dashes: ┄┄┄ ┅┅┅ ┈┈┈ ┉┉┉ ╌╌╌ ╍╍╍ ╎╏ ┆┇ ┊┋  diagonals: ╱╲╳")
    p("blocks: " + "".join(chr(c) for c in range(0x2580, 0x25A0)))
    p("eighths ▁▂▃▄▅▆▇█ ▏▎▍▌▋▊▉█  shades ░▒▓█  quadrants ▖▗▘▙▚▛▜▝▞▟")
    p("legacy computing (U+1FB00-): " + "".join(chr(c) for c in range(0x1FB00, 0x1FB20)))
    p("smooth mosaics, octants: " + "".join(chr(c) for c in range(0x1FB3C, 0x1FB50)) + " " + "".join(chr(c) for c in range(0x1CD00, 0x1CD10)))
    p("braille: " + "".join(chr(c) for c in range(0x2800, 0x2840)))
    p("braille: " + "".join(chr(c) for c in range(0x2840, 0x2880)))
    p("braille: " + "".join(chr(c) for c in range(0x28C0, 0x2900)))
    p("powerline:              ")
    p(f"{ESC}[44;97m main {ESC}[34;42m{ESC}[30;42m +3 {ESC}[32;43m{ESC}[30;43m ~1 {ESC}[33;49m{ESC}[0m")
    p("nerd/devicons (PUA):    ")
def text():
    p("CJK wide, then a marker that must line up:")
    p("日本語のテキスト|")
    p("1234567890123456|")
    p("한글 텍스트 中文字符|")
    p("emoji: 😀 🎉 🚀 ✅ ❌ ⚠️ ❤️ 👍🏽")
    p("ZWJ: 👨‍👩‍👧‍👦 👩‍💻 🧑🏽‍🚀 🏳️‍🌈 🏴‍☠️ |")
    p("12345678901234567890|")
    p("flags: 🇺🇸 🇯🇵 🇸🇪 🇧🇷 |")
    p("1234567890123|")
    p("combining: é ä ñ ô ū ẋ̣ Z͑ͫ̓ͤ |")
    p("1234567890123456789012|")
    p("devanagari क्ष कि arabic مرحبا hebrew שלום thai สวัสดี")
    p("VS16 text vs emoji: ❤ ❤️ ☺ ☺️ keycap 1️⃣ |")
def styles():
    p(f"regular {ESC}[1mbold{ESC}[0m {ESC}[3mitalic{ESC}[0m {ESC}[1;3mbold italic{ESC}[0m")
    p(f"{ESC}[4msingle underline{ESC}[0m {ESC}[4:2mdouble underline{ESC}[0m {ESC}[4:3mcurly underline{ESC}[0m")
    p(f"{ESC}[4:4mdotted underline{ESC}[0m {ESC}[4:5mdashed underline{ESC}[0m")
    p(f"{ESC}[4:3;58;2;255;0;0mred curly{ESC}[0m {ESC}[4;58;5;46mgreen single{ESC}[0m")
    p(f"{ESC}[9mstrikethrough{ESC}[0m {ESC}[53moverline{ESC}[0m {ESC}[5mblink{ESC}[0m {ESC}[6mfast blink{ESC}[0m")
    p(f"{ESC}[1;4;9;31mbold under strike red{ESC}[0m")
    p(f"plain {ESC}]8;;https://example.com/osc8{ESC}\\OSC 8 link{ESC}]8;;{ESC}\\ plain")
    p(f"{ESC}]8;id=a;https://example.com/a{ESC}\\second link with id{ESC}]8;;{ESC}\\")
    p("tab\tstops\tline\tup")
    p("wrap: " + "x" * 200)
def cursor(style):
    sys.stdout.write(f"cursor DECSCUSR {style}: \n> ")
    sys.stdout.write(f"{ESC}[{style} q")
sec = sys.argv[1]
if sec == "cursor": cursor(sys.argv[2])
else: {"colors": colors, "box": box, "text": text, "styles": styles}[sec]()
sys.stdout.flush()
time.sleep(float(sys.argv[3]) if len(sys.argv) > 3 else 6)
