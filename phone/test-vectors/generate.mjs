// Writes TBD's own phone-channel test vectors: confirmation-code.json,
// pairing-link.json and framing.json. With --check, builds them in memory,
// compares each with the file on disk byte for byte, and exits 1 on the first
// that differs.
//
// This script uses only Node built-ins and raw Web Crypto calls, and never
// imports from phone/loader/. That independence is what makes the Swift and
// JS tests that read these files a real cross-check.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const subtle = globalThis.crypto.subtle;
const encoder = new TextEncoder();
const generatedNote = 'Generated by generate.mjs; do not edit by hand.';

/** @param {Uint8Array} bytes */
const toHex = (bytes) => Buffer.from(bytes).toString('hex');
/** @param {string} hex */
const fromHex = (hex) => new Uint8Array(Buffer.from(hex, 'hex'));
/** Base64url with no padding. @param {Uint8Array} bytes */
const base64url = (bytes) => Buffer.from(bytes).toString('base64url');
/** The bytes first through last, inclusive. @param {number} first @param {number} last */
const byteRange = (first, last) => Uint8Array.from({ length: last - first + 1 }, (_, i) => first + i);

const cacophony = JSON.parse(readFileSync(new URL('noise-cacophony.json', import.meta.url), 'utf8'));

/** @param {string} protocolName */
function cacophonyVector(protocolName) {
  const vector = cacophony.vectors.find((/** @type {any} */ v) => v.protocol_name === protocolName);
  if (!vector) throw new Error(`noise-cacophony.json has no ${protocolName} vector`);
  return vector;
}

const ikVector = cacophonyVector('Noise_IK_25519_AESGCM_SHA256');
const ikpsk2Vector = cacophonyVector('Noise_IKpsk2_25519_AESGCM_SHA256');

// MARK: confirmation-code.json

/** @param {Uint8Array} handshakeHash */
function confirmationCode(handshakeHash) {
  const leading = new DataView(handshakeHash.buffer, handshakeHash.byteOffset, 4).getUint32(0, false);
  return String(leading % 1_000_000).padStart(6, '0');
}

function confirmationCodeVectors() {
  const filler = '11'.repeat(28);
  const inputs = [
    ['the cacophony Noise_IK_25519_AESGCM_SHA256 handshake hash', ikVector.handshake_hash],
    ['the cacophony Noise_IKpsk2_25519_AESGCM_SHA256 handshake hash', ikpsk2Vector.handshake_hash],
    ['leading UInt32 0 gives the smallest code', `00000000${filler}`],
    ['leading UInt32 42 is zero-padded to six digits', `0000002a${filler}`],
    ['leading UInt32 999,999,999 gives the largest code', `3b9ac9ff${filler}`],
    ['leading UInt32 1,000,000,000 wraps to zero', `3b9aca00${filler}`],
    ['leading UInt32 0xffffffff is read unsigned and big-endian', `ffffffff${filler}`],
  ];
  return {
    description:
      'Phone confirmation code: the first 4 bytes of the 32-byte Noise handshake hash, read as a big-endian ' +
      `UInt32, modulo 1,000,000, zero-padded to 6 digits with no space. ${generatedNote}`,
    cases: inputs.map(([description, handshakeHash]) => ({
      description,
      handshakeHash,
      code: confirmationCode(fromHex(handshakeHash)),
    })),
  };
}

// MARK: pairing-link.json

const loaderURL = 'https://acme-loader.github.io/';
const now = 1_800_000_000;

const mainLink = {
  v: 1,
  relay: 'https://acme-relay.acme.workers.dev',
  room: base64url(byteRange(0x00, 0x1f)),
  secret: base64url(byteRange(0x20, 0x3f)),
  key: base64url(fromHex(ikVector.init_remote_static)),
  name: 'Acme’s MacBook Pro',
  exp: now + 300,
};

/**
 * JSON text whose keys were inserted in sorted order, so the bytes match
 * Swift's JSONEncoder with [.sortedKeys, .withoutEscapingSlashes].
 * @param {Record<string, unknown>} object
 */
function sortedJSON(object) {
  /** @type {Record<string, unknown>} */
  const sorted = {};
  for (const key of Object.keys(object).sort()) sorted[key] = object[key];
  return JSON.stringify(sorted);
}

/** @param {string} text */
const textPayload = (text) => base64url(encoder.encode(text));
/** @param {Record<string, unknown>} object */
const linkPayload = (object) => textPayload(sortedJSON(object));
/** @param {string} payload */
const linkURL = (payload) => `${loaderURL}#p=${payload}`;
/** The main link with some fields replaced. @param {Record<string, unknown>} fields */
const changedLinkURL = (fields) => linkURL(linkPayload({ ...mainLink, ...fields }));

function pairingLinkVectors() {
  const mainPayload = linkPayload(mainLink);

  let truncatedLength = mainPayload.length - 1;
  while (truncatedLength % 4 !== 1) truncatedLength -= 1;

  const { room: _room, ...linkWithoutRoom } = mainLink;
  if (!mainLink.room.endsWith('8')) throw new Error('the room no longer ends in 8; revisit the spare-bits case');

  const v2Link = { ...mainLink, relay: 'http://localhost:8787', name: 'a', exp: now + 1 };

  const invalid = [
    { description: 'no fragment', url: loaderURL, error: 'missingFragment' },
    { description: 'the fragment key is q, not p', url: `${loaderURL}#q=${mainPayload}`, error: 'missingFragment' },
    { description: 'the payload carries = padding', url: linkURL(`${mainPayload}=`), error: 'badBase64' },
    {
      description: 'the payload uses the standard alphabet character +',
      url: linkURL(`+${mainPayload.slice(1)}`),
      error: 'badBase64',
    },
    {
      description: `the payload is cut to ${truncatedLength} characters, a length of 1 mod 4`,
      url: linkURL(mainPayload.slice(0, truncatedLength)),
      error: 'badBase64',
    },
    { description: 'the payload bytes fffe7b7d are not UTF-8', url: linkURL(base64url(fromHex('fffe7b7d'))), error: 'badJSON' },
    { description: 'the payload JSON is an array, not an object', url: linkURL(textPayload('[1]')), error: 'badJSON' },
    {
      description: 'v is 2',
      url: linkURL(textPayload('{"v":2,"relay":"https://acme-relay.acme.workers.dev"}')),
      error: 'unsupportedVersion',
    },
    { description: 'v is the string "1", not a number', url: changedLinkURL({ v: '1' }), error: 'badJSON' },
    { description: 'the room key is missing', url: linkURL(linkPayload(linkWithoutRoom)), error: 'badJSON' },
    {
      description: 'the relay is plain http on a host that is not loopback',
      url: changedLinkURL({ relay: 'http://acme-relay.acme.workers.dev' }),
      error: 'badField',
      field: 'relay',
    },
    {
      description: 'the relay scheme is ftp',
      url: changedLinkURL({ relay: 'ftp://acme-relay.acme.workers.dev' }),
      error: 'badField',
      field: 'relay',
    },
    {
      description: 'the room is cut to 42 characters',
      url: changedLinkURL({ room: mainLink.room.slice(0, 42) }),
      error: 'badField',
      field: 'room',
    },
    {
      description: 'the room ends in 9, not 8, so its spare bits are non-zero',
      url: changedLinkURL({ room: `${mainLink.room.slice(0, -1)}9` }),
      error: 'badField',
      field: 'room',
    },
    {
      description: 'the secret carries = padding',
      url: changedLinkURL({ secret: `${mainLink.secret}=` }),
      error: 'badField',
      field: 'secret',
    },
    {
      description: 'the key decodes to 31 bytes',
      url: changedLinkURL({ key: base64url(new Uint8Array(31).fill(0x01)) }),
      error: 'badField',
      field: 'key',
    },
    { description: 'the name is empty', url: changedLinkURL({ name: '' }), error: 'badField', field: 'name' },
    {
      description: 'the name is 257 UTF-8 bytes',
      url: changedLinkURL({ name: 'x'.repeat(257) }),
      error: 'badField',
      field: 'name',
    },
    { description: 'exp is 0', url: changedLinkURL({ exp: 0 }), error: 'badField', field: 'exp' },
    { description: 'exp equals now', url: changedLinkURL({ exp: now }), error: 'expired' },
  ];

  return {
    description:
      'Pairing links: <loaderURL>#p=<base64url(UTF-8 JSON)>, base64url without padding, JSON keys sorted. ' +
      'Each valid url parses at now (unix seconds) to link, ignoring unknown fields; a canonical link also ' +
      'encodes back to url. Each invalid url fails with error, and with field for badField. Field checks run ' +
      'in the order relay, room, secret, key, name, exp. base64url lists strict decoder cases: valid text ' +
      `decodes to hex, and each invalid text decodes to nothing. ${generatedNote}`,
    loaderURL,
    now,
    base64url: {
      valid: ['', '00', '0001', '000102', 'fbff'].map((hex) => ({ text: base64url(fromHex(hex)), hex })),
      invalid: ['A', 'AA==', 'AAE=', '+/8', 'AB', ' AA', 'AA\n'],
    },
    valid: [
      { description: 'V1: the main link', link: mainLink, url: linkURL(mainPayload), canonical: true },
      {
        description: 'V2: a loopback http relay, a one-character name, and exp one second after now',
        link: v2Link,
        url: linkURL(linkPayload(v2Link)),
        canonical: true,
      },
      {
        description: 'V3: an unknown field is ignored',
        link: mainLink,
        url: changedLinkURL({ future: true }),
        canonical: false,
      },
    ],
    invalid,
  };
}

// MARK: framing.json

async function framingVectors() {
  const keyBytes = byteRange(0x00, 0x1f);
  const key = await subtle.importKey('raw', keyBytes, 'AES-GCM', false, ['encrypt']);
  /** @type {[bigint, string][]} */
  const inputs = [
    [0n, '{"type":"hello","loaderVersion":"1.0.0","protocols":[1]}'],
    [1n, ''],
    [2n, '{"type":"app","body":{"text":"café ✓"}}'],
    [2n ** 32n, '{"type":"app","body":{"kind":"event","event":"sessions.changed","seq":7,"data":{}}}'],
    [2n ** 64n - 2n, '{"type":"revoked"}'],
  ];
  const messages = [];
  for (const [nonce, plaintext] of inputs) {
    const iv = new Uint8Array(12);
    new DataView(iv.buffer).setBigUint64(4, nonce, false);
    const ciphertext = new Uint8Array(await subtle.encrypt({ name: 'AES-GCM', iv }, key, encoder.encode(plaintext)));
    messages.push({ nonce: nonce.toString(), plaintext, ciphertext: toHex(ciphertext) });
  }

  const roomID = byteRange(0x20, 0x3f);
  const prologue = new Uint8Array([...encoder.encode('tbd-phone/1'), ...roomID]);
  return {
    description:
      'Noise transport messages: AES-256-GCM under key, with a 12-byte nonce of 4 zero bytes followed by the ' +
      '64-bit counter, big-endian, and empty associated data. ciphertext is the encrypted bytes followed by the ' +
      '16-byte tag. Nonces are decimal strings because 2^64-2 does not survive a JS number. prologue is UTF-8 ' +
      `"tbd-phone/1" followed by the 32 raw room-ID bytes. ${generatedNote}`,
    key: toHex(keyBytes),
    messages,
    prologue: { roomID: base64url(roomID), prologue: toHex(prologue) },
  };
}

// MARK: main

const files = {
  'confirmation-code.json': confirmationCodeVectors(),
  'pairing-link.json': pairingLinkVectors(),
  'framing.json': await framingVectors(),
};

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  process.stderr.write('usage: node generate.mjs [--check]\n');
  process.exit(2);
}
const check = args.length === 1;

for (const [name, value] of Object.entries(files)) {
  const url = new URL(name, import.meta.url);
  const expected = Buffer.from(`${JSON.stringify(value, null, 2)}\n`, 'utf8');
  if (!check) {
    writeFileSync(url, expected);
    continue;
  }
  let actual;
  try {
    actual = readFileSync(url);
  } catch {
    actual = null;
  }
  if (!actual || !actual.equals(expected)) {
    process.stderr.write(`${fileURLToPath(url)} differs from what generate.mjs builds; run npm run vectors\n`);
    process.exit(1);
  }
}
