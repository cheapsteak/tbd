def manifest_entry(scenario: Scenario, data: bytes, session: PtySession, extra: dict) -> dict:
    answered = []
    unanswered = []
    for tally in sorted(session.queries.values(), key=lambda t: (t.label, t.sequence)):
        if tally.reply is not None:
            answered.append({"query": tally.label, "sequence": tally.sequence, "reply": visible(tally.reply),
                             "count": tally.count})
        else:
            unanswered.append({"query": tally.label, "sequence": tally.sequence, "count": tally.count})
    entry = {
        "name": scenario.name,
        "file": f"{scenario.name}.vt",
        "cols": scenario.cols,
        "rows": scenario.rows,
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
        "description": scenario.description,
        "tool": extra.get("tool", "unknown"),
        "exit_status": session.status,
        "answered": answered,
        "unanswered": unanswered,
        "exercises": features(session.sequences, strip_escapes(data)),
    }
    if extra.get("stub_requests") is not None:
        entry["stub_requests"] = extra["stub_requests"]
    return entry


def record(names: list[str], out_dir: Path, debug_dir: Path | None = None) -> int:
    chosen = [s for s in SCENARIOS if not names or s.name in names]
    unknown = set(names) - {s.name for s in SCENARIOS}
    if unknown:
        print(f"unknown scenario(s): {', '.join(sorted(unknown))}", file=sys.stderr)
        return 2
    results: list[tuple[Scenario, bytes, dict]] = []
    findings: list[str] = []
    for scenario in chosen:
        box = Sandbox.create()
        try:
            print(f"recording {scenario.name} ({scenario.cols}x{scenario.rows})", file=sys.stderr)
            session, extra = scenario.run(scenario, box)
            data = bytes(session.output)
            for needle in scenario.required:
                if needle not in data:
                    raise ScenarioError(f"{scenario.name}: the recording lacks {visible(needle)}")
            if len(data) > MAX_SCENARIO_BYTES:
                raise ScenarioError(f"{scenario.name}: {len(data)} bytes, over {MAX_SCENARIO_BYTES}")
            findings += privacy_findings(scenario.name, data, private_words(box.root))
            results.append((scenario, data, manifest_entry(scenario, data, session, extra)))
        except ScenarioError as error:
            print(f"{scenario.name}: {error}", file=sys.stderr)
            if PtySession.current is not None and debug_dir is not None:
                debug_dir.mkdir(parents=True, exist_ok=True)
                partial = debug_dir / f"{scenario.name}.partial.vt"
                partial.write_bytes(bytes(PtySession.current.output))
                print(f"{scenario.name}: what it printed is in {partial}", file=sys.stderr)
            return 1
        finally:
            box.remove()
    if findings:
        print("privacy scan failed; nothing was written:", file=sys.stderr)
        for finding in findings:
            print(f"  {finding}", file=sys.stderr)
        return 1
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = out_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    entries = {entry["name"]: entry for entry in manifest.get("recordings", [])}
    for scenario, data, entry in results:
        (out_dir / f"{scenario.name}.vt").write_bytes(data)
        entries[scenario.name] = entry
    order = [s.name for s in SCENARIOS]
    recordings = [entries[name] for name in order if name in entries]
    total = sum(entry["bytes"] for entry in recordings)
    if total > MAX_TOTAL_BYTES:
        print(f"the corpus is {total} bytes, over {MAX_TOTAL_BYTES}", file=sys.stderr)
        return 1
    manifest = {
        "about": (
            "Recorded terminal output for the emulator parity suite. Each .vt file holds only the bytes "
            "the program wrote to its pty, recorded by scripts/record-emulator-parity-corpus.py, which "
            "documents the environment, the keystrokes and the query answers. Feed a file to a fresh "
            "terminal of the listed size."
        ),
        "recorder": "scripts/record-emulator-parity-corpus.py",
        "platform": f"{platform.system()} {platform.machine()}",
        "answers": {
            "DA1": visible(DA1_REPLY),
            "DA2": visible(DA2_REPLY),
            "XTVERSION": visible(XTVERSION_REPLY),
            "DSR": visible(DSR_REPLY),
            "CPR": visible(CPR_REPLY) + " (fixed: the recorder runs no emulator)",
            "DECRQM ?2026": "ESC[?2026;2$y, or ESC[?2026;1$y while DEC 2026 is set",
            "OSC 7501 probe": visible(OSC7501_PROBE_REPLY),
        },
        "recordings": recordings,
    }
    manifest_text = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    manifest_findings = privacy_findings("manifest.json", manifest_text.encode(), private_words(None))
    if manifest_findings:
        print("privacy scan of the manifest failed:", file=sys.stderr)
        for finding in manifest_findings:
            print(f"  {finding}", file=sys.stderr)
        return 1
    manifest_path.write_text(manifest_text, encoding="utf-8")
    for scenario, data, entry in results:
        print(f"{scenario.name}: {len(data)} bytes, sha256 {entry['sha256'][:16]}", file=sys.stderr)
    return 0


def scan(out_dir: Path) -> int:
    words = private_words(None)
    findings: list[str] = []
    files = sorted(out_dir.glob("*.vt")) + [out_dir / "manifest.json"]
    for path in files:
        if path.exists():
            findings += privacy_findings(path.name, path.read_bytes(), words)
    for finding in findings:
        print(finding, file=sys.stderr)
    print(f"scanned {len(files)} file(s): {'clean' if not findings else f'{len(findings)} finding(s)'}", file=sys.stderr)
    return 1 if findings else 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("scenarios", nargs="*", help=f"scenarios to record (default: all of {', '.join(s.name for s in SCENARIOS)})")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="where to write the recordings and manifest")
    parser.add_argument("--scan", action="store_true", help="only scan the recordings in --out for private content")
    parser.add_argument("--debug-dir", type=Path, help="on a failure, write what the program printed here (not scanned)")
    args = parser.parse_args(argv)
    if args.scan:
        return scan(args.out)
    return record(args.scenarios, args.out, args.debug_dir)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
