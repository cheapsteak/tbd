def visible(data: bytes) -> str:
    """Escape bytes spelled out for the manifest: ESC (with a space before a
    letter or backslash, so `ESC P` is not read as a word), BEL, and \\xNN."""
    out = []
    for index, byte in enumerate(data):
        if byte == 0x1B:
            following = data[index + 1:index + 2]
            out.append("ESC " if following.isalpha() or following == b"\\" else "ESC")
        elif byte == 0x07:
            out.append("BEL")
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append(f"\\x{byte:02x}")
    return "".join(out)


# --- a scanner for escape sequences ----------------------------------------


@dataclass
class Sequence:
    """One complete escape sequence from the child's output."""

    kind: str  # "csi", "osc", "dcs", "apc", "pm", "sos", "esc"
    raw: bytes
    params: bytes = b""
    intermediates: bytes = b""
    final: int = 0
    data: bytes = b""  # the payload of a string sequence


class VTScanner:
    """Splits a byte stream into escape sequences, keeping its state across
    chunks, so a query split over two reads is still seen once and whole."""

    STRING_KINDS = {ord("]"): "osc", ord("P"): "dcs", ord("_"): "apc", ord("^"): "pm", ord("X"): "sos"}
    MAX_STRING = 1 << 16

    def __init__(self) -> None:
        self.state = "ground"
        self.raw = bytearray()
        self.params = bytearray()
        self.intermediates = bytearray()
        self.data = bytearray()
        self.kind = ""

    def _start(self, state: str) -> None:
        self.state = state
        self.params.clear()
        self.intermediates.clear()
        self.data.clear()

    def feed(self, chunk: bytes) -> list[Sequence]:
        found: list[Sequence] = []
        for byte in chunk:
            self._step(byte, found)
        return found

    def _step(self, byte: int, found: list[Sequence]) -> None:
        state = self.state
        if state == "ground":
            if byte == 0x1B:
                self.raw = bytearray(b"\x1b")
                self._start("esc")
            return
        self.raw.append(byte)
        if state == "esc":
            if byte == ord("["):
                self._start("csi")
            elif byte in self.STRING_KINDS:
                self.kind = self.STRING_KINDS[byte]
                self._start("string")
            elif 0x20 <= byte <= 0x2F:
                self._start("esc_int")
                self.intermediates.append(byte)
            elif 0x30 <= byte <= 0x7E:
                found.append(Sequence("esc", bytes(self.raw), final=byte))
                self.state = "ground"
            elif byte == 0x1B:
                self.raw = bytearray(b"\x1b")
            elif byte in (0x18, 0x1A):
                self.state = "ground"
            return
        if state == "esc_int":
            if 0x20 <= byte <= 0x2F:
                self.intermediates.append(byte)
            elif 0x30 <= byte <= 0x7E:
                found.append(Sequence("esc", bytes(self.raw), intermediates=bytes(self.intermediates), final=byte))
                self.state = "ground"
            elif byte == 0x1B:
                self.raw = bytearray(b"\x1b")
                self._start("esc")
            elif byte in (0x18, 0x1A):
                self.state = "ground"
            return
        if state == "csi":
            if 0x30 <= byte <= 0x3F:
                self.params.append(byte)
            elif 0x20 <= byte <= 0x2F:
                self.intermediates.append(byte)
            elif 0x40 <= byte <= 0x7E:
                found.append(
                    Sequence("csi", bytes(self.raw), bytes(self.params), bytes(self.intermediates), byte)
                )
                self.state = "ground"
            elif byte == 0x1B:
                self.raw = bytearray(b"\x1b")
                self._start("esc")
            elif byte in (0x18, 0x1A):
                self.state = "ground"
            if len(self.raw) > 512:
                self.state = "ground"
            return
        if state == "string":
            if byte == 0x07 and self.kind == "osc":
                found.append(Sequence(self.kind, bytes(self.raw), data=bytes(self.data)))
                self.state = "ground"
            elif byte == 0x1B:
                self.state = "string_esc"
            elif byte in (0x18, 0x1A):
                self.state = "ground"
            elif len(self.data) < self.MAX_STRING:
                self.data.append(byte)
            return
        if state == "string_esc":
            if byte == ord("\\"):
                found.append(Sequence(self.kind, bytes(self.raw), data=bytes(self.data)))
                self.state = "ground"
            else:
                # An ESC that is not ST ends the string unterminated and
                # starts a new sequence.
                self.raw = bytearray(b"\x1b")
                self._start("esc")
                self._step(byte, found)


# --- queries ------------------------------------------------------------------

# XTWINOPS operations that ask for a report rather than act.
XTWINOPS_REPORTS = {b"11", b"13", b"14", b"15", b"16", b"18", b"19", b"20", b"21"}
COLOUR_OSCS = {b"4", b"5", b"10", b"11", b"12", b"13", b"14", b"15", b"16", b"17", b"18", b"19"}


def classify(seq: Sequence, modes: set[bytes]) -> tuple[str, bytes | None] | None:
    """(label, reply) for a query, reply None when it goes unanswered; None
    when the sequence asks nothing. `modes` holds the DEC private modes the
    stream has set so far."""
    if seq.kind == "csi":
        params = seq.params
        prefix = params[:1] if params[:1] in (b"<", b"=", b">", b"?") else b""
        rest = params[len(prefix):]
        inter = seq.intermediates
        final = chr(seq.final)
        if inter == b"" and final == "c":
            if prefix == b"" and rest in (b"", b"0"):
                return "DA1 (primary device attributes)", DA1_REPLY
            if prefix == b">" and rest in (b"", b"0"):
                return "DA2 (secondary device attributes)", DA2_REPLY
            if prefix == b"=":
                return "DA3 (tertiary device attributes)", None
        if inter == b"" and final == "q" and prefix == b">" and rest in (b"", b"0"):
            return "XTVERSION (terminal name and version)", XTVERSION_REPLY
        if inter == b"" and final == "n":
            if prefix == b"" and rest == b"5":
                return "DSR (device status report)", DSR_REPLY
            if prefix == b"" and rest == b"6":
                return "CPR (cursor position report)", CPR_REPLY
            return f"DSR {visible(params)}n", None
        if inter == b"$" and final == "p":
            if params == b"?2026":
                state = b"1" if b"2026" in modes else b"2"
                return "DECRQM ?2026 (synchronized output)", b"\x1b[?2026;" + state + b"$y"
            return f"DECRQM {visible(params)}", None
        if inter == b"" and final == "u" and prefix == b"?":
            return "kitty keyboard flags query", None
        if inter == b"" and final == "m" and prefix == b"?":
            return "XTQMODKEYS (modifier key mode query)", None
        if inter == b"" and final == "t" and prefix == b"" and rest.split(b";")[0] in XTWINOPS_REPORTS:
            return f"XTWINOPS {visible(rest)}t (window report)", None
        if inter == b"" and final == "S" and prefix == b"?":
            return "XTSMGRAPHICS (graphics attribute query)", None
        if inter == b"" and final == "x" and prefix == b"":
            return "DECREQTPARM", None
        return None
    if seq.kind == "osc":
        code, _, payload = seq.data.partition(b";")
        if code == b"7501":
            if payload == b"?":
                return "OSC 7501 probe (program status)", OSC7501_PROBE_REPLY
            return None
        if code in COLOUR_OSCS and payload.split(b";")[-1:] == [b"?"]:
            return f"OSC {code.decode()} colour query", None
        if code == b"52" and payload.endswith(b";?"):
            return "OSC 52 clipboard read", None
        return None
    if seq.kind == "apc" and seq.data.startswith(b"G") and b"a=q" in seq.data.split(b";")[0]:
        return "kitty graphics query", None
    if seq.kind == "dcs":
        if seq.data.startswith(b"$q"):
            return f"DECRQSS {visible(seq.data[2:])}", None
        if seq.data.startswith(b"+q"):
            names = []
            for name in seq.data[2:].split(b";"):
                try:
                    names.append(bytes.fromhex(name.decode()).decode("ascii", "replace"))
                except ValueError:
                    names.append(visible(name))
            return f"XTGETTCAP {','.join(names)}", None
        return None
    return None


