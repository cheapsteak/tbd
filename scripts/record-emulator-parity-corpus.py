def is_wide(char: str) -> bool:
    code = ord(char)
    return (
        0x1100 <= code <= 0x115F
        or 0x2E80 <= code <= 0xA4CF
        or 0xAC00 <= code <= 0xD7A3
        or 0xF900 <= code <= 0xFAFF
        or 0xFE30 <= code <= 0xFE4F
        or 0xFF00 <= code <= 0xFF60
        or 0x1F300 <= code <= 0x1FAFF
    )


def strip_escapes(data: bytes, separator: str = "") -> str:
    """The printed text: every escape sequence and control replaced by
    `separator`. The privacy scan separates with a space, because a TUI moves
    the cursor between words instead of printing spaces, and a word glued to
    its neighbours would slip past a whole-word match."""
    text = data.decode("utf-8", "replace")
    text = re.sub(r"\x1b\][^\x07\x1b]*(\x07|\x1b\\)", separator, text)
    text = re.sub(r"\x1b[P_^X][^\x1b]*\x1b\\", separator, text)
    text = re.sub(r"\x1b\[[0-?]*[ -/]*[@-~]", separator, text)
    text = re.sub(r"\x1b[ -/]*[0-~]", separator, text)
    return re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", separator, text)


# --- privacy ----------------------------------------------------------------------

MONTHS = "jan|feb|mar|apr|may|jun|jul|aug|sep|sept|oct|nov|dec|january|february|march|april|june|july|august|september|october|november|december"
DATE_PATTERNS = [
    re.compile(r"\b(19|20)\d\d[-/.](0?[1-9]|1[0-2])[-/.](0?[1-9]|[12]\d|3[01])\b"),
    re.compile(r"\b(0?[1-9]|1[0-2])/(0?[1-9]|[12]\d|3[01])/(19|20)?\d\d\b"),
    re.compile(rf"\b({MONTHS})\.? +(0?[1-9]|[12]\d|3[01])\b", re.IGNORECASE),
    re.compile(rf"\b(0?[1-9]|[12]\d|3[01]) +({MONTHS})\b", re.IGNORECASE),
]
TIME_PATTERN = re.compile(r"\b([01]?\d|2[0-3]):[0-5]\d(:[0-5]\d)?\b|\b(1[0-2]|0?[1-9]) ?[ap]\.?m\.?\b", re.IGNORECASE)
EMAIL_PATTERN = re.compile(rb"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")
HOME_PATTERN = re.compile(rb"/Users/|/home/[a-z]|/var/folders/|/private/var/")


def private_words(temp_root: Path | None) -> list[str]:
    """What must never appear: who and where this machine is."""
    words: set[str] = set()
    user = getpass.getuser()
    words.add(user)
    try:
        gecos = pwd.getpwnam(user).pw_gecos
        words.update(part for part in re.split(r"[\s,]+", gecos) if len(part) >= 3)
    except KeyError:
        pass
    host = socket.gethostname()
    words.add(host)
    words.add(host.split(".")[0])
    words.add(str(Path.home()))
    try:
        email = subprocess.run(
            ["git", "config", "user.email"], capture_output=True, text=True, cwd=REPO_ROOT, check=False
        ).stdout.strip()
    except OSError:
        email = ""
    if email:
        words.add(email)
        local, _, domain = email.partition("@")
        words.add(local)
        if domain and domain not in ("users.noreply.github.com", "gmail.com"):
            words.add(domain.split(".")[0])
    extra = os.environ.get("EMULATOR_PARITY_PRIVATE_WORDS", "")
    words.update(word.strip() for word in extra.split(",") if word.strip())
    if temp_root is not None:
        words.add(str(temp_root))
        words.add(str(temp_root.resolve()))
    return sorted({word.lower(): word for word in words if len(word) >= 3}.values())


def privacy_findings(name: str, data: bytes, words: list[str]) -> list[str]:
    """Whole-word matches, over the raw bytes and over the printed text, so a
    word is found whether an escape sequence or a space sits beside it."""
    findings = []
    text = strip_escapes(data, separator=" ")
    lowered = [data.decode("utf-8", "replace").lower(), text.lower()]
    for word in words:
        pattern = re.compile(r"(?<![a-z0-9])" + re.escape(word.lower()) + r"(?![a-z0-9])")
        if any(pattern.search(haystack) for haystack in lowered):
            findings.append(f"{name}: names a private word ({len(word)} characters, starts with {word[:1]!r})")
    if HOME_PATTERN.search(data):
        findings.append(f"{name}: holds a home or temporary path: {HOME_PATTERN.search(data).group().decode()}")
    match = EMAIL_PATTERN.search(data)
    if match:
        findings.append(f"{name}: holds an email address")
    for pattern in DATE_PATTERNS:
        match = pattern.search(text)
        if match:
            findings.append(f"{name}: holds a date: {match.group()!r}")
    match = TIME_PATTERN.search(text)
    if match:
        findings.append(f"{name}: holds a time of day: {match.group()!r}")
    return findings


# --- a pty session ----------------------------------------------------------------


class ScenarioError(RuntimeError):
    pass


@dataclass
class QueryTally:
    label: str
    sequence: str
    reply: bytes | None
    count: int = 0


class PtySession:
    """One child in one pty: what it prints is recorded, what it asks is answered."""

    # The session of the scenario being recorded, so a failure can show what
    # the program had printed.
    current: "PtySession | None" = None

    def __init__(self, argv: list[str], env: dict[str, str], cwd: Path, cols: int, rows: int) -> None:
        PtySession.current = self
        self.output = bytearray()
        self.scanner = VTScanner()
        self.sequences: list[Sequence] = []
        self.queries: dict[tuple[str, str], QueryTally] = {}
        self.modes: set[bytes] = set()
        self.eof = False
        self.status: int | None = None
        executable = shutil.which(argv[0], path=env.get("PATH")) if "/" not in argv[0] else argv[0]
        if executable is None:
            raise ScenarioError(f"{argv[0]} is not on the scenario's PATH")
        winsize = struct.pack("HHHH", rows, cols, 0, 0)
        pid, fd = os.forkpty()
        if pid == 0:  # the child
            try:
                fcntl.ioctl(0, termios.TIOCSWINSZ, winsize)
                os.chdir(cwd)
                os.execve(executable, argv, env)
            finally:
                os._exit(127)
        self.pid = pid
        self.fd = fd
        fcntl.ioctl(fd, termios.TIOCSWINSZ, winsize)

    # Reading -------------------------------------------------------------------

    def _read_once(self, timeout: float) -> bool:
        """Read what is there within `timeout`; True when something came."""
        if self.eof:
            return False
        readable, _, _ = select.select([self.fd], [], [], max(0.0, timeout))
        if not readable:
            return False
        try:
            chunk = os.read(self.fd, 65536)
        except OSError:
            chunk = b""
        if not chunk:
            self.eof = True
            return False
        self.output.extend(chunk)
        replies = bytearray()
        for seq in self.scanner.feed(chunk):
            self.sequences.append(seq)
            if seq.kind == "csi" and seq.params.startswith(b"?") and seq.final in (ord("h"), ord("l")) \
                    and not seq.intermediates:
                for mode in seq.params[1:].split(b";"):
                    (self.modes.add if seq.final == ord("h") else self.modes.discard)(mode)
            classified = classify(seq, self.modes)
            if classified is None:
                continue
            label, reply = classified
            key = (label, visible(seq.raw))
            tally = self.queries.setdefault(key, QueryTally(label, visible(seq.raw), reply))
            tally.count += 1
            if reply is not None:
                replies.extend(reply)
        if replies:
            self.write(bytes(replies))
        return True

    def settle(
        self,
        until: bytes | Callable[[bytes], bool] | None = None,
        since: int = 0,
        quiet: float = 0.6,
        limit: float = 15.0,
        what: str = "",
    ) -> None:
        """Read until `until` holds for the output after `since` (a substring,
        or a predicate over those bytes), then until nothing comes for `quiet`
        seconds. Bounded by `limit` seconds; an unmet `until` is an error, a
        program that never goes quiet is not."""
        deadline = time.monotonic() + limit

        def met() -> bool:
            if until is None:
                return True
            tail = bytes(self.output[since:])
            return until in tail if isinstance(until, bytes) else until(tail)

        while not met():
            if time.monotonic() >= deadline or self.eof:
                raise ScenarioError(f"timed out waiting for {what or until!r}")
            self._read_once(min(0.2, deadline - time.monotonic()))
        last = time.monotonic()
        while time.monotonic() < deadline and not self.eof:
            if self._read_once(min(quiet, deadline - time.monotonic())):
                last = time.monotonic()
            elif time.monotonic() - last >= quiet:
                return

    def mark(self) -> int:
        return len(self.output)

    # Writing -------------------------------------------------------------------

    def write(self, data: bytes) -> None:
        view = memoryview(data)
        while view:
            written = os.write(self.fd, view)
            view = view[written:]

    def send(self, data: bytes, **settle_args) -> None:
        """Type `data`, then settle."""
        mark = self.mark()
        self.write(data)
        self.settle(since=mark, **settle_args)

    # Ending ----------------------------------------------------------------------

    def finish(self, limit: float = 10.0) -> int:
        """Read until the child has exited and the pty is drained."""
        deadline = time.monotonic() + limit
        while time.monotonic() < deadline:
            if self.status is None:
                pid, status = os.waitpid(self.pid, os.WNOHANG)
                if pid:
                    self.status = os.waitstatus_to_exitcode(status)
            if self.eof and self.status is not None:
                break
            if self.eof:
                time.sleep(0.05)  # the pty has closed; the exit is a moment behind
            elif not self._read_once(0.1) and self.status is not None:
                # Exited and nothing more within 0.1 s: drain what is left.
                while self._read_once(0.05):
                    pass
                break
        if self.status is None:
            self.kill()
            raise ScenarioError("the program did not exit")
        os.close(self.fd)
        return self.status

    def kill(self) -> None:
        try:
            os.kill(self.pid, signal.SIGKILL)
            os.waitpid(self.pid, 0)
        except (ProcessLookupError, ChildProcessError):
            pass
        try:
            os.close(self.fd)
        except OSError:
            pass


