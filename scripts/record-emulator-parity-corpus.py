#!/usr/bin/env python3
"""Record the byte streams of the emulator parity corpus.

What it does
------------
The parity suite (docs/specs/2026-11-13-swiftterm-retirement-design.md, section
C, "Gates and the flip") feeds recorded terminal output through the daemon's two
emulators, SwiftTerm and libghostty-vt, and compares the screens, the styled
captures, the modes, the OSC 7501 reports and the replies to the child. This
script makes those recordings. For each scenario it:

- starts the program in a fresh pty of a fixed size, with a fixed environment:
  `TERM=xterm-256color`, `LANG`/`LC_ALL=en_US.UTF-8`, a sandbox `HOME` in a
  temporary directory, the working directory `~/acme-project` inside it, and
  no user configuration (`bash --norc --noprofile` with a fixed `PS1`, `vim -u`
  the vimrc below, `less` with `LESS` unset and `LESSHISTFILE=-`);
- types a fixed script of keystrokes, waiting between steps for the program to
  go quiet or to say what the step waits for, every wait bounded;
- answers the program's terminal queries as TBD's emulators answer them (see
  "Queries" below), because a session under TBD gets those answers and a
  program changes what it prints by them;
- writes only what the program printed, the bytes read from the pty master, to
  `Tests/TBDDaemonTests/Fixtures/EmulatorParity/<scenario>.vt`, and describes
  each recording in `manifest.json` beside them.

Scenarios: `claude-stub` (the Claude Code TUI against the fake model API,
`scripts/claude-stub.py`), `vim`, `less` and `colour-log` (a bash session that
runs a colour log script). Every input is generated by this file: no recording
comes from a real session, and none reads a file it did not write. Claude Code
runs with a fixed session id and a settings file that fixes its spinner verb
and turns off its spinner tips and its turn footer, because those are picked at
random or print the time of day.

Why the recordings are committed
--------------------------------
The recorded bytes are the test input. A re-recording is not always
byte-identical: how many animation frames a TUI prints depends on the timing of
its redraws (in Claude Code, the welcome animation and the spinner's shimmer).
Committing the bytes makes the parity test deterministic by construction and
lets it run in CI, where `claude`, `vim` and `less` may be missing or at other
versions. The manifest pins each file's size and SHA-256, so a test can tell a
fixture that changed from one that was re-recorded on purpose.

Re-recording
------------
    scripts/record-emulator-parity-corpus.py               # every scenario
    scripts/record-emulator-parity-corpus.py vim less      # only these
    scripts/record-emulator-parity-corpus.py --out DIR     # elsewhere, e.g. to compare two runs
    scripts/record-emulator-parity-corpus.py --scan        # only the privacy scan of the fixtures
    scripts/record-emulator-parity-corpus.py --debug-dir DIR claude-stub
                                                           # keep what a failed scenario printed

Needs python3 (stdlib only), /bin/bash, /usr/bin/vim, /usr/bin/less, and
`claude` on PATH for the `claude-stub` scenario. The tools' versions go into
the manifest, so a re-recording on another version shows up in its diff.
Review the manifest diff and the parity test's result, then commit the `.vt`
files with the manifest.

Privacy
-------
The repository is public. Before anything is written, every recording is
scanned and the run fails if it holds the user's name, the host's name, a home
path (`/Users/...`, `/home/...`), the temporary directory's path, an email
address, a date or a time of day, or any word listed in the environment
variable `EMULATOR_PARITY_PRIVATE_WORDS` (comma-separated: an employer, a
client, anything this repository may not name). Claude Code runs with its own
`HOME` and `CLAUDE_CONFIG_DIR` inside the sandbox and never sees the real
configuration, and its only network peer is the stub on loopback.

Queries
-------
Answered, with the bytes SwiftTerm answers with in the daemon today (DA1,
DA2 and XTVERSION are TBD's frozen device identity, which both emulators send):

- DA1 `CSI c` / `CSI 0 c` -> `CSI ? 65 ; 4 ; 1 ; 2 ; 6 ; 21 ; 22 ; 17 ; 28 c`
- DA2 `CSI > c` / `CSI > 0 c` -> `CSI > 65 ; 20 ; 1 c`
- XTVERSION `CSI > q` / `CSI > 0 q` -> `DCS > | SwiftTerm+b4db5b0ecd62: ST`
- DSR `CSI 5 n` -> `CSI 0 n`
- CPR `CSI 6 n` -> `CSI 1 ; 1 R`. A fixed position, because this script runs no
  emulator to know the real one; the top-left cell is what a program sees on a
  fresh screen. The parity test compares the two emulators' own replies, not
  this one.
- DECRQM `CSI ? 2026 $ p` -> `CSI ? 2026 ; 2 $ y` (reset), or `; 1` while the
  stream has DEC 2026 set, as SwiftTerm reports it.
- the OSC 7501 probe `OSC 7501 ; ?` -> `OSC 7501 ; ? BEL`
  (`ProgramStatusProtocol.probeReply` in Sources/TBDShared/ProgramStatus.swift).

Three of these decide what Claude Code prints: it sends OSC 7501 state
reports only after the probe is answered, and it wraps its frames in DEC 2026
synchronized output only when XTVERSION is answered (without that answer it
never asks) and the DECRQM reply then reports mode 2026 (Claude Code 2.1.325).

Every other query is left unanswered and listed in the manifest under
`unanswered`.
"""

