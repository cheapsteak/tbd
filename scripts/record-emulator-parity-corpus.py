@dataclass
class Sandbox:
    """A temporary HOME and a neutral working directory beside nothing real."""

    root: Path
    home: Path
    project: Path

    @classmethod
    def create(cls) -> "Sandbox":
        # Resolved, so the working directory a program reads back is spelled
        # the way HOME is, and a TUI shows it as `~/acme-project`.
        root = Path(tempfile.mkdtemp(prefix="parity-")).resolve()
        home = root / "home"
        project = home / "acme-project"
        project.mkdir(parents=True)
        (home / "tmp").mkdir()
        return cls(root, home, project)

    def base_env(self) -> dict[str, str]:
        return {
            "HOME": str(self.home),
            "USER": "acme",
            "LOGNAME": "acme",
            "SHELL": "/bin/bash",
            "PATH": "/usr/bin:/bin:/usr/sbin:/sbin",
            "TERM": "xterm-256color",
            "LANG": "en_US.UTF-8",
            "LC_ALL": "en_US.UTF-8",
            "TMPDIR": str(self.home / "tmp"),
            "PWD": str(self.project),
        }

    def remove(self) -> None:
        shutil.rmtree(self.root, ignore_errors=True)


