#!/usr/bin/env python3
"""Embed the session mod's source into Sources/TBDShared/SessionModContent.swift.

The daemon writes the session mod into the `tbd` plugin directory from that
Swift file, so the TypeScript under SessionMod/ is the source of truth and the
Swift file is generated from it: every file under SessionMod/hooks/ (dotfiles
excluded) plus SessionMod/types/index.d.ts, keyed by its path relative to the
plugin root and sorted by that path. Each body is a Swift raw string whose `#`
count no sequence in the file can close or escape.

    python3 scripts/gen-session-mod-content.py          # rewrite the Swift file
    python3 scripts/gen-session-mod-content.py --check  # exit 1 if it is stale

The `session-mod` CI job runs `--check`.
"""

import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "SessionMod"
OUTPUT = ROOT / "Sources" / "TBDShared" / "SessionModContent.swift"
OUTPUT_NAME = OUTPUT.relative_to(ROOT).as_posix()

HEADER = "// Generated by scripts/gen-session-mod-content.py from SessionMod/. Do not edit."


def mod_files():
    """(path relative to the plugin root, text) for each embedded file, sorted."""
    paths = [
        path
        for path in (MOD / "hooks").rglob("*")
        if path.is_file() and not any(part.startswith(".") for part in path.relative_to(MOD).parts)
    ]
    paths.append(MOD / "types" / "index.d.ts")
    files = []
    for path in paths:
        text = path.read_bytes().decode("utf-8")
        if "\r" in text:
            sys.exit(f"{path.relative_to(ROOT)}: carriage returns are not embedded; use LF line endings")
        files.append((path.relative_to(MOD).as_posix(), text))
    return sorted(files)


def hash_count(text):
    # The fewest `#`s whose raw-string delimiter and escape the text never
    # spells: a Swift raw string ends at a quote followed by that many `#`s,
    # and reads a backslash followed by that many `#`s as an escape, so
    # neither may appear in the text.
    count = 1
    while ('"' + "#" * count) in text or ("\\" + "#" * count) in text:
        count += 1
    return count


def swift_source():
    entries = []
    for path, text in mod_files():
        hashes = "#" * hash_count(text)
        # The line break before the closing delimiter is not part of the
        # string, so the text is followed by one of its own.
        entries.append(f'        (path: "{path}", body: {hashes}"""\n{text}\n"""{hashes}),\n')
    return (
        f"{HEADER}\n"
        "\n"
        "/// The session mod, the hooks module of the `tbd` Claude Code plugin, and\n"
        "/// the contract its plugin manifest names: each file's path relative to the\n"
        "/// plugin root and its exact content, sorted by path. The source is\n"
        "/// `SessionMod/`; `PluginDirWriter` writes these files while a session-mod\n"
        "/// feature flag is on.\n"
        "public enum SessionModContent {\n"
        "    public static let files: [(path: String, body: String)] = [\n"
        f"{''.join(entries)}"
        "    ]\n"
        "}\n"
    )


def main(argv):
    if argv not in ([], ["--check"]):
        sys.exit("usage: gen-session-mod-content.py [--check]")
    source = swift_source()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if argv == ["--check"]:
        if current == source:
            return 0
        diff = difflib.unified_diff(
            current.splitlines(keepends=True),
            source.splitlines(keepends=True),
            fromfile=f"{OUTPUT_NAME} (committed)",
            tofile=f"{OUTPUT_NAME} (from SessionMod/)",
        )
        sys.stdout.writelines(list(diff)[:60])
        print(
            f"\n{OUTPUT_NAME} is stale: run `python3 scripts/gen-session-mod-content.py` and commit the result.",
            file=sys.stderr,
        )
        return 1
    if current != source:
        OUTPUT.write_text(source, encoding="utf-8")
        print(f"wrote {OUTPUT_NAME}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
